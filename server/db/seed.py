def seed(db_path: Path = DB_PATH) -> int:
    """写入居民人设，返回写入数量。幂等，可重复运行。"""
    with sqlite3.connect(db_path) as conn:
        for r in RESIDENTS:
            conn.execute(
                """
                INSERT OR REPLACE INTO residents
                    (id, name, occupation, personality, backstory, prompt_prefix,
                     current_location, current_action, daily_plan)
                VALUES (?, ?, ?, ?, ?, ?, ?, NULL, NULL)
                """,
                (
                    r["id"],
                    r["name"],
                    r["occupation"],
                    r["personality"],
                    r["backstory"],
                    r["prompt_prefix"],
                    r["current_location"],
                ),
            )
    return len(RESIDENTS)


