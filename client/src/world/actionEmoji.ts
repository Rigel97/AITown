// - planner 生成的动作是自由中文短语（"给门口的花圃浇水"），不可能逐条枚举，
//   所以用"关键词命中"：按 RULES 顺序首个命中即返回——排在前面的规则优先，
//   多义词靠排序消歧（"浇花"先命中 花→🌸，"浇水"才落到 浇→💧）。
// - 全部未命中时回退职业默认 emoji（world_state 会下发 occupation），
//   再兜底 🚶——保证头顶永远有"这个人正在干嘛"的信号。
// - 纯函数、零依赖：服务端任何动作文案变化只需增删关键词行，不动渲染层。

