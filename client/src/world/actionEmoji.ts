/** 职业关键词 → 默认 emoji（动作无命中时兜底） */
const OCCUPATION_RULES: ReadonlyArray<readonly [string, string]> = [
  ["面包", "🥐"],
  ["图书", "📖"],
  ["花", "🌸"],
  ["邮", "✉️"],
  ["餐", "🍳"],
  ["厨", "🍳"],
  ["学徒", "📝"],
  ["杂货", "📦"],
  ["木匠", "🔨"],
];

const DEFAULT_EMOJI = "🚶";

/** 动作文本 → emoji；未命中关键词时回退职业默认，再兜底 🚶 */
export function actionEmoji(action: string, occupation = ""): string {
  for (const [keyword, emoji] of ACTION_RULES) {
    if (action.includes(keyword)) return emoji;
  }
  for (const [keyword, emoji] of OCCUPATION_RULES) {
    if (occupation.includes(keyword)) return emoji;
  }
  return DEFAULT_EMOJI;
}
